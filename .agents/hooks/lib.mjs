// Shared policy for Hearthwild Antigravity hooks (doctrine DOC-1, TEAM-2, TEAM-5, TEAM-7).
// Doctrine-protected: only Claude/director edit this file.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const HOOKS_DIR = path.dirname(fileURLToPath(import.meta.url));
export const AGENTS_DIR = path.dirname(HOOKS_DIR);
export const REPO_ROOT = path.resolve(process.env.HEARTHWILD_REPO_ROOT ?? path.dirname(AGENTS_DIR));
export const STATE_DIR = path.resolve(process.env.HEARTHWILD_STATE_DIR ?? path.join(AGENTS_DIR, 'state'));
export const ROLES = ['blender', 'communicator'];
const CASE_INSENSITIVE = process.platform === 'win32';

export function readStdin() {
  try {
    const raw = readFileSync(0, 'utf8');
    return raw.trim() ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
}

export function emit(obj) {
  process.stdout.write(JSON.stringify(obj));
}

export function readRole() {
  const env = process.env.HEARTHWILD_ROLE?.trim();
  if (env && ROLES.includes(env)) return env;
  try {
    const role = readFileSync(path.join(STATE_DIR, 'role'), 'utf8').trim();
    return ROLES.includes(role) ? role : null;
  } catch {
    return null;
  }
}

export function loadState(name, fallback) {
  try {
    return JSON.parse(readFileSync(path.join(STATE_DIR, name), 'utf8'));
  } catch {
    return fallback;
  }
}

export function saveState(name, value) {
  mkdirSync(STATE_DIR, { recursive: true });
  writeFileSync(path.join(STATE_DIR, name), JSON.stringify(value, null, 2));
}

// Tool arguments sometimes arrive JSON-encoded ("\"path\""); unwrap them.
export function arg(args, ...keys) {
  for (const key of keys) {
    let v = args?.[key];
    if (typeof v === 'string' && v.length >= 2 && v.startsWith('"') && v.endsWith('"')) {
      try {
        v = JSON.parse(v);
      } catch {
        /* keep raw */
      }
    }
    if (v !== undefined && v !== null && v !== '') return v;
  }
  return undefined;
}

/** Repo-relative POSIX path, or null when the path is outside the repository. */
export function repoRel(p) {
  if (typeof p !== 'string' || !p) return null;
  let s = p.trim();
  if (s.startsWith('file://')) s = fileURLToPath(s);
  const abs = path.resolve(REPO_ROOT, s);
  let rel = path.relative(REPO_ROOT, abs);
  if (rel.startsWith('..') || path.isAbsolute(rel)) return null;
  rel = rel.split(path.sep).join('/');
  return CASE_INSENSITIVE ? rel.toLowerCase() : rel;
}

function globToRegExp(glob) {
  const g = CASE_INSENSITIVE ? glob.toLowerCase() : glob;
  let re = '';
  for (let i = 0; i < g.length; i++) {
    const c = g[i];
    if (c === '*' && g[i + 1] === '*') {
      re += '.*';
      i++;
      if (g[i + 1] === '/') i++;
    } else if (c === '*') re += '[^/]*';
    else re += c.replace(/[.+^${}()|[\]\\?]/g, '\\$&');
  }
  return new RegExp(`^${re}$`);
}

export const match = (rel, globs) => globs.some((g) => globToRegExp(g).test(rel));

