/** Returns null when the role may write rel directly, otherwise a denial reason. */
export function writeDenial(role, rel) {
  if (rel === null) return null; // outside the repo: the agent's own artifacts/scratch
  if (match(rel, PROTECTED) && !match(rel, PROTECTED_EXCEPTIONS)) {
    return `${rel} is doctrine-protected (DOC-1). Agents never edit it. Propose changes in docs/team/proposals/ (DOC-3).`;
  }
  const comms = rel.match(/^docs\/team\/comms\/([^/]+)\//);
  if (comms && comms[1] !== role) {
    return `${rel} belongs to ${comms[1]}'s comms folder. Write only in docs/team/comms/${role}/ (TEAM-3).`;
  }
  if (!role) {
    return 'No role is set for this machine. Ask the director which role you are, then run: node .agents/hooks/set-role.mjs <blender|communicator>.';
  }
  if (match(rel, LANES[role] ?? [])) return null;
  if (match(rel, VIA_TOOL_ONLY[role] ?? [])) {
    return `${rel} is written only by \`forge.py publish\` after a director approval record exists (L7, TEAM-2).`;
  }
  return `${rel} is outside the ${role} lane (TEAM-2). Ask its owner via docs/team/comms/${role}/ instead.`;
}

/** Same as writeDenial but also accepts tool-generated paths (used by the stop check). */
export function changeDenial(role, rel) {
  if (match(rel, GENERATED)) return null;
  if (role === 'blender' && match(rel, VIA_TOOL_ONLY.blender)) return null; // checked against approvals separately
  return writeDenial(role, rel);
}

export const BANNED =
  /\bAAA(-grade|-quality)?\b|\bstellar\b|\bflawless(ly)?\b|\bperfect(ly)?\b|\bproduction-ready\b|\bworld-class\b|\bstunning\b|\bgorgeous\b/i;

/** First line containing a banned superlative (TEAM-5.3), ignoring lines that cite the rule itself. */
export function bannedLine(text) {
  if (typeof text !== 'string') return null;
  for (const line of text.split(/\r?\n/)) {
    if (BANNED.test(line) && !/TEAM-5\.3|banned/i.test(line)) return line.trim().slice(0, 160);
  }
  return null;
}

export function sha256File(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

export function gitChangedPaths() {
  try {
    const out = execFileSync('git', ['status', '--porcelain', '-uall'], { cwd: REPO_ROOT, encoding: 'utf8' });
    return out
      .split('\n')
      .filter(Boolean)
      .map((l) => l.slice(3).split(' -> ').pop().replace(/^"|"$/g, ''))
      .map((p) => (CASE_INSENSITIVE ? p.toLowerCase() : p));
  } catch {
    return [];
  }
}

export function roleCard(role) {
  const file = path.join(HOOKS_DIR, 'role-cards', `${role ?? 'unset'}.md`);
  return existsSync(file) ? readFileSync(file, 'utf8') : '';
}
